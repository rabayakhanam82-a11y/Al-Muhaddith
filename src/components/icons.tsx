/**
 * Typographic collection mark: the collection's initial Arabic letter set in
 * the display serif inside a hairline square. Purely a letter, not an emoji.
 */
export function CollectionGlyph({
  glyph,
  size = "md",
}: {
  glyph: string;
  size?: "sm" | "md";
}) {
  const box = size === "sm" ? "h-5 w-5 text-[11px]" : "h-7 w-7 text-sm";
  return (
    <span
      aria-hidden="true"
      className={`inline-grid shrink-0 place-items-center border border-hairline bg-ink-sunken font-arabic leading-none text-gold ${box}`}
    >
      {glyph}
    </span>
  );
}
